#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const OUT = join(process.cwd(), '..', 'audit', '2026-09-08');
const AGENTS = Number(process.env.REVIEW_AGENTS ?? 8);

function walk(dir) {
  const out = [];
  const rec = (d) => {
    let entries = [];
    try {
      entries = readdirSync(d);
    } catch {
      return;
    }
    for (const e of entries) {
      const full = join(d, e);
      if (statSync(full).isDirectory()) rec(full);
      else if (e.endsWith('.png')) out.push(full);
    }
  };
  rec(dir);
  return out;
}

const files = [...walk(join(OUT, 'screens')), ...walk(join(OUT, 'states'))].sort();

const byHash = new Map();
for (const f of files) {
  const h = createHash('md5').update(readFileSync(f)).digest('hex');
  if (!byHash.has(h)) byHash.set(h, []);
  byHash.get(h).push(relative(OUT, f));
}

function partsOf(rel) {
  const p = rel.split(sep);
  return { kind: p[0], role: p[1] ?? '', route: p[2] ?? '', file: p[p.length - 1] };
}

const representatives = [];
for (const [hash, group] of byHash) {
  const sorted = [...group].sort();
  const rep = sorted[0];
  const meta = partsOf(rep);
  representatives.push({
    hash,
    file: rep,
    kind: meta.kind,
    role: meta.role,
    route: meta.route,
    copies: sorted.length,
    identicalTo: sorted.slice(1),
    rolesSharing: [...new Set(sorted.map((f) => partsOf(f).role))].sort(),
  });
}

const byRoute = new Map();
for (const r of representatives) {
  const key = r.route || '(none)';
  if (!byRoute.has(key)) byRoute.set(key, []);
  byRoute.get(key).push(r);
}

const routes = [...byRoute.entries()]
  .map(([route, imgs]) => ({ route, images: imgs.length, files: imgs }))
  .sort((a, b) => b.images - a.images);

const buckets = Array.from({ length: AGENTS }, () => ({ routes: [], images: 0 }));
for (const r of routes) {
  const target = buckets.reduce((a, b) => (a.images <= b.images ? a : b));
  target.routes.push(r.route);
  target.images += r.images;
}

mkdirSync(join(OUT, 'findings'), { recursive: true });
writeFileSync(
  join(OUT, 'findings', 'review-manifest.json'),
  JSON.stringify(
    {
      generated: new Date().toISOString(),
      totalImages: files.length,
      distinctImages: representatives.length,
      duplicatesSkipped: files.length - representatives.length,
      routes: routes.map((r) => ({ route: r.route, images: r.images })),
      buckets: buckets.map((b, i) => ({ agent: i + 1, images: b.images, routes: b.routes })),
      representatives,
    },
    null,
    2,
  ),
);

const L = [];
L.push('# Review manifest for the 2026-09-08 captures');
L.push('');
L.push('Generated by `tests/audit/review-manifest.mjs`. This is the list Goal 9 reads, and the count it must report against.');
L.push('');
L.push('| | |');
L.push('| :---- | ----: |');
L.push(`| Images captured | ${files.length} |`);
L.push(`| Distinct images by content hash | ${representatives.length} |`);
L.push(`| Byte-identical copies not read twice | ${files.length - representatives.length} |`);
L.push(`| Routes with at least one image | ${routes.length} |`);
L.push(`| Review buckets | ${AGENTS} |`);
L.push('');
L.push('An image byte-identical to one already read is not read again; the representative records which roles share it, so a finding on it applies to all of them. That is the only deduplication applied: nothing is skipped for being similar, only for being the same bytes.');
L.push('');
L.push('## Images per route, largest first');
L.push('');
L.push('| Route | Distinct images |');
L.push('| :---- | ----: |');
for (const r of routes) L.push(`| \`${r.route}\` | ${r.images} |`);
L.push('');
L.push('## Buckets');
L.push('');
L.push('| Bucket | Images | Routes |');
L.push('| ----: | ----: | :---- |');
for (const [i, b] of buckets.entries()) {
  L.push(`| ${i + 1} | ${b.images} | ${b.routes.map((r) => `\`${r}\``).join(', ')} |`);
}
L.push('');
writeFileSync(join(OUT, 'findings', 'REVIEW-MANIFEST.md'), L.join('\n'));

console.log(
  `images=${files.length} distinct=${representatives.length} duplicates=${files.length - representatives.length} routes=${routes.length} buckets=${AGENTS}`,
);
console.log(`wrote ${join(OUT, 'findings', 'REVIEW-MANIFEST.md')} and review-manifest.json`);
